PatientPanel::PatientPanel(controller::ClinicManager& manager, QWidget* parent)
    : QWidget(parent), manager_(manager)
{
    buildUi();
    refresh();
    clearForm();
}

void PatientPanel::buildUi()
{
    auto* rootLayout = new QVBoxLayout(this);

    table_ = new QTableWidget(this);
    table_->setColumnCount(6);
    table_->setHorizontalHeaderLabels({tr("ID"), tr("Name"), tr("Age"), tr("Contact"),
                                       tr("Category"), tr("Details")});
    table_->setSelectionBehavior(QAbstractItemView::SelectRows);
    table_->setSelectionMode(QAbstractItemView::SingleSelection);
    table_->setToolTip(tr("Select a patient row to view or edit that record."));
    table_->setEditTriggers(QAbstractItemView::NoEditTriggers);
    table_->horizontalHeader()->setSectionResizeMode(QHeaderView::Stretch);
    table_->verticalHeader()->setVisible(false);
    rootLayout->addWidget(table_, 3);

    formLayout_ = new QFormLayout();
    idEdit_ = new QLineEdit(this);
    idEdit_->setReadOnly(true);
    idEdit_->setToolTip(tr("Patient IDs are generated by the system."));
    nameEdit_ = new QLineEdit(this);
    nameEdit_->setPlaceholderText(tr("Enter patient's full name"));
    nameEdit_->setToolTip(tr("Enter a non-empty patient name."));
    ageEdit_ = new QLineEdit(this);
    ageEdit_->setPlaceholderText(tr("Whole number from 0 to 120"));
    ageEdit_->setToolTip(tr("Enter a whole-number age from 0 through 120."));
    contactEdit_ = new QLineEdit(this);
    contactEdit_->setPlaceholderText(tr("Phone or other contact details"));
    contactEdit_->setToolTip(tr("Enter a phone/contact value with 7 to 15 digits."));
    categoryCombo_ = new QComboBox(this);
    categoryCombo_->addItems({tr("General"), tr("Emergency"), tr("Follow-up")});
    categoryCombo_->setToolTip(tr("Choose the patient type and its required details."));

    generalReasonEdit_ = new QLineEdit(this);
    generalReasonEdit_->setToolTip(tr("Describe the reason for this general visit."));
    severitySpin_ = new QSpinBox(this);
    severitySpin_->setRange(1, 5);
    severitySpin_->setToolTip(tr("Emergency severity from 1 (most severe) to 5."));
    emergencyDetailsEdit_ = new QLineEdit(this);
    emergencyDetailsEdit_->setToolTip(tr("Describe the emergency."));
    previousVisitEdit_ = new QLineEdit(this);
    previousVisitEdit_->setToolTip(tr("Enter the ID of the previous visit."));
    followUpReasonEdit_ = new QLineEdit(this);
    followUpReasonEdit_->setToolTip(tr("Describe the reason for the follow-up."));

    formLayout_->addRow(tr("ID:"), idEdit_);
    formLayout_->addRow(tr("Name:"), nameEdit_);
    formLayout_->addRow(tr("Age:"), ageEdit_);
    formLayout_->addRow(tr("Contact:"), contactEdit_);
    formLayout_->addRow(tr("Category:"), categoryCombo_);
    formLayout_->addRow(tr("Reason for visit:"), generalReasonEdit_);
    formLayout_->addRow(tr("Severity (1–5):"), severitySpin_);
    formLayout_->addRow(tr("Emergency details:"), emergencyDetailsEdit_);
    formLayout_->addRow(tr("Previous visit ID:"), previousVisitEdit_);
    formLayout_->addRow(tr("Follow-up reason:"), followUpReasonEdit_);
    rootLayout->addLayout(formLayout_);

    auto* buttonLayout = new QHBoxLayout();
    addButton_ = new QPushButton(tr("Add"), this);
    editButton_ = new QPushButton(tr("Edit"), this);
    deleteButton_ = new QPushButton(tr("Delete"), this);
    undoButton_ = new QPushButton(tr("Undo"), this);
    clearButton_ = new QPushButton(tr("Clear Form"), this);
    addButton_->setToolTip(tr("Register a new patient record."));
    editButton_->setToolTip(tr("Save changes to the selected patient."));
    deleteButton_->setToolTip(tr("Delete the selected patient and their appointments."));
    undoButton_->setToolTip(tr("Undo the last patient edit, deletion, or appointment removal."));
    clearButton_->setToolTip(tr("Clear the form and prepare a new patient ID."));
    buttonLayout->addWidget(addButton_);
    buttonLayout->addWidget(editButton_);
    buttonLayout->addWidget(deleteButton_);
    buttonLayout->addWidget(undoButton_);
    buttonLayout->addWidget(clearButton_);
    rootLayout->addLayout(buttonLayout);
    rootLayout->addWidget(new QLabel(
        tr("Legend: Emergency — light red; Follow-up — light blue."), this));

    connect(categoryCombo_, &QComboBox::currentTextChanged,
            this, &PatientPanel::onCategoryChanged);
    connect(table_, &QTableWidget::currentCellChanged,
            this, &PatientPanel::onCurrentCellChanged);
    connect(addButton_, &QPushButton::clicked, this, &PatientPanel::addPatient);
    connect(editButton_, &QPushButton::clicked, this, &PatientPanel::editPatient);
    connect(deleteButton_, &QPushButton::clicked, this, &PatientPanel::deletePatient);
    connect(undoButton_, &QPushButton::clicked, this, &PatientPanel::undoLastOperation);
    connect(clearButton_, &QPushButton::clicked, this, &PatientPanel::clearForm);

    onCategoryChanged(categoryCombo_->currentText());
}

void PatientPanel::refresh()
{
    const std::string selectedId = selectedPatientId_;
    const auto patients = manager_.getPatients();
    const QSignalBlocker blocker(table_);
    table_->setRowCount(0);
    int selectedRow = -1;

    for (const auto* patient : patients) {
        const int row = table_->rowCount();
        table_->insertRow(row);
        const QString values[] = {
            QString::fromStdString(patient->getId()),
            QString::fromStdString(patient->getName()),
            QString::number(patient->getAge()),
            QString::fromStdString(patient->getContact()),
            QString::fromStdString(patient->getCategory()),
            QString::fromStdString(patient->describe())
        };
        for (int column = 0; column < 6; ++column) {
            auto* item = new QTableWidgetItem(values[column]);
            if (column == 2) item->setTextAlignment(Qt::AlignCenter);
            table_->setItem(row, column, item);
        }
        setRowCategoryColor(row, values[4]);
        if (patient->getId() == selectedId) selectedRow = row;
    }

    if (selectedRow >= 0) {
        table_->setCurrentCell(selectedRow, 0);
        selectedPatientId_ = selectedId;
        const auto* patient = manager_.database().findById(selectedId);
        if (patient) populateForm(*patient);
    } else {
        selectedPatientId_.clear();
        clearForm();
    }
}

void PatientPanel::onCategoryChanged(const QString& category)
{
    const bool general = category == tr("General");
    const bool emergency = category == tr("Emergency");
    const bool followUp = category == tr("Follow-up");
    auto setRowVisible = [this](QWidget* field, bool visible) {
        field->setVisible(visible);
        if (QWidget* label = formLayout_->labelForField(field)) label->setVisible(visible);
    };
    setRowVisible(generalReasonEdit_, general);
    setRowVisible(severitySpin_, emergency);
    setRowVisible(emergencyDetailsEdit_, emergency);
    setRowVisible(previousVisitEdit_, followUp);
    setRowVisible(followUpReasonEdit_, followUp);
}

void PatientPanel::onCurrentCellChanged(int currentRow, int, int, int)
{
    if (currentRow < 0) {
        selectedPatientId_.clear();
        return;
    }
    const auto* item = table_->item(currentRow, 0);
    if (!item) return;
    selectedPatientId_ = item->text().toStdString();
    const auto* patient = manager_.database().findById(selectedPatientId_);
    if (patient) {
        (void)manager_.getPatients(); // A table selection is a patient view for the recent cache.
        populateForm(*patient);
    }
}

std::unique_ptr<model::PatientRecord> PatientPanel::makePatient(const std::string& id) const
{
    const std::string name = nameEdit_->text().trimmed().toStdString();
    scapms::utils::Validator::validateName(name);
    bool ageOk = false;
    const int age = ageEdit_->text().trimmed().toInt(&ageOk);
    if (!ageOk) throw model::ValidationException("Patient age must be a whole number.");
    scapms::utils::Validator::validateAge(age);
    const std::string contact = contactEdit_->text().trimmed().toStdString();
    const QString category = categoryCombo_->currentText();
    scapms::utils::Validator::validateContact(contact);

    if (category == tr("General")) {
        return std::make_unique<model::GeneralPatient>(
            id, name, age, contact, generalReasonEdit_->text().trimmed().toStdString());
    }
    if (category == tr("Emergency")) {
        return std::make_unique<model::EmergencyPatient>(
            id, name, age, contact, severitySpin_->value(),
            emergencyDetailsEdit_->text().trimmed().toStdString());
    }
    return std::make_unique<model::FollowUpPatient>(
        id, name, age, contact, previousVisitEdit_->text().trimmed().toStdString(),
        followUpReasonEdit_->text().trimmed().toStdString());
}

void PatientPanel::populateForm(const model::PatientRecord& patient)
{
    idEdit_->setText(QString::fromStdString(patient.getId()));
    nameEdit_->setText(QString::fromStdString(patient.getName()));
    ageEdit_->setText(QString::number(patient.getAge()));
    contactEdit_->setText(QString::fromStdString(patient.getContact()));
    categoryCombo_->setCurrentText(QString::fromStdString(patient.getCategory()));

    if (const auto* general = dynamic_cast<const model::GeneralPatient*>(&patient)) {
        generalReasonEdit_->setText(QString::fromStdString(general->getReasonForVisit()));
        emergencyDetailsEdit_->clear();
        previousVisitEdit_->clear();
        followUpReasonEdit_->clear();
    } else if (const auto* emergency = dynamic_cast<const model::EmergencyPatient*>(&patient)) {
        severitySpin_->setValue(emergency->getSeverityLevel());
        emergencyDetailsEdit_->setText(QString::fromStdString(emergency->getEmergencyDetails()));
        generalReasonEdit_->clear();
        previousVisitEdit_->clear();
        followUpReasonEdit_->clear();
    } else if (const auto* followUp = dynamic_cast<const model::FollowUpPatient*>(&patient)) {
        previousVisitEdit_->setText(QString::fromStdString(followUp->getPreviousVisitId()));
        followUpReasonEdit_->setText(QString::fromStdString(followUp->getFollowUpReason()));
        generalReasonEdit_->clear();
        emergencyDetailsEdit_->clear();
    }
}

void PatientPanel::setRowCategoryColor(int row, const QString& category)
{
    QColor color;
    if (category == tr("Emergency")) color = QColor(QStringLiteral("#ffe0e0"));
    else if (category == tr("Follow-up")) color = QColor(QStringLiteral("#e0f0ff"));
    if (!color.isValid()) return;
    for (int column = 0; column < table_->columnCount(); ++column) {
        table_->item(row, column)->setBackground(color);
    }
}

void PatientPanel::showException(const model::ValidationException& error)
{
    QMessageBox::warning(this, tr("Patient validation error"),
                         tr("Error: %1").arg(QString::fromUtf8(error.what())));
}

void PatientPanel::addPatient()
{
    try {
        const std::string id = idEdit_->text().toStdString();
        manager_.registerPatient(makePatient(id));
        selectedPatientId_.clear();
        refresh();
        emit patientsChanged();
    } catch (const model::DuplicateIdException&) {
        QMessageBox::warning(this, tr("Patient error"), tr("Error: Patient ID already exists."));
    } catch (const model::ValidationException& error) {
        showException(error);
    }
}

void PatientPanel::editPatient()
{
    if (selectedPatientId_.empty()) {
        QMessageBox::warning(this, tr("Edit patient"), tr("Select a patient row first."));
        return;
    }
    try {
        manager_.editPatient(makePatient(selectedPatientId_));
        refresh();
        emit patientsChanged();
    } catch (const model::DuplicateIdException&) {
        QMessageBox::warning(this, tr("Patient error"), tr("Error: Patient ID already exists."));
    } catch (const model::ValidationException& error) {
        showException(error);
    }
}

void PatientPanel::deletePatient()
{
    if (selectedPatientId_.empty()) {
        QMessageBox::warning(this, tr("Delete patient"), tr("Select a patient row first."));
        return;
    }
    try {
        if (!manager_.deletePatient(selectedPatientId_)) {
            QMessageBox::warning(this, tr("Delete patient"), tr("Selected patient was not found."));
            return;
        }
        selectedPatientId_.clear();
        refresh();
        emit patientsChanged();
    } catch (const model::DuplicateIdException&) {
        QMessageBox::warning(this, tr("Patient error"), tr("Error: Patient ID already exists."));
    } catch (const model::ValidationException& error) {
        showException(error);
    }
}

void PatientPanel::undoLastOperation()
{
    try {
        if (!manager_.undoLastOperation()) {
            QMessageBox::warning(this, tr("Undo"), tr("There is no administrative operation to undo."));
            return;
        }
        refresh();
        emit patientsChanged();
    } catch (const model::DuplicateIdException&) {
        QMessageBox::warning(this, tr("Patient error"), tr("Error: Patient ID already exists."));
    } catch (const model::ValidationException& error) {
        showException(error);
    }
}

void PatientPanel::clearForm()
{
    selectedPatientId_.clear();
    table_->clearSelection();
    table_->setCurrentCell(-1, -1);
    idEdit_->setText(QString::fromStdString(scapms::utils::IDGenerator::nextPatientId()));
    nameEdit_->clear();
    ageEdit_->clear();
    contactEdit_->clear();
    categoryCombo_->setCurrentIndex(0);
    generalReasonEdit_->clear();
    severitySpin_->setValue(1);
    emergencyDetailsEdit_->clear();
    previousVisitEdit_->clear();
    followUpReasonEdit_->clear();
}

